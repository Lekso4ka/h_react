export const LANG_KEY = "hotel_lang";

export function readStoredLang() {
    try {
        return localStorage.getItem(LANG_KEY) === "en" ? "en" : "ru";
    } catch {
        return "ru";
    }
}

export function writeStoredLang(lang) {
    try {
        localStorage.setItem(LANG_KEY, lang === "en" ? "en" : "ru");
    } catch {
        /* ignore */
    }
}

